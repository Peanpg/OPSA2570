import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports = {};
const js = ts.transpileModule(fs.readFileSync('lib/measurement-site.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
vm.runInNewContext(js,{exports});
const { isMeasurementSite, meterVoltageStatus } = exports;
const points = JSON.parse(fs.readFileSync('app/transformers.json','utf8'));
const sites = JSON.parse(fs.readFileSync('app/measurement-sites.json','utf8'));
const coverage = JSON.parse(fs.readFileSync('app/meter-coverage.json','utf8'));
assert.equal(points.length,43);
assert.equal(sites.length,43);
assert.equal(coverage.length,43);
assert.equal(new Set(sites.map(s=>s.transformerPea)).size,43);
assert.equal(coverage.filter(p=>p.lowMeterCount===0).length,19);
assert.ok(sites.every(isMeasurementSite));
assert.ok(sites.every(s=>points.some(p=>p.pea===s.transformerPea)));
assert.equal(sites.filter(s=>s.voltage<200).length,24);
assert.equal(sites.filter(s=>s.voltage>=200).length,19);
assert.ok(points.every(p=>p.reportedProblem?.trim() && p.problemSource==='DB_OPSA70' && p.problemSourceDate==='2026-11-06'));
assert.equal(points.filter(p=>p.reportedProblem.startsWith('2.')).length,27);
assert.equal(points.filter(p=>p.reportedProblem.startsWith('3.')).length,16);
assert.ok(sites.every(s=>s.phase.length===1));
assert.ok(sites.every(s=>s.lat>16&&s.lat<18&&s.long>102&&s.long<104));
assert.ok(sites.every(s=>s.lat!==points.find(p=>p.pea===s.transformerPea).lat || s.long!==points.find(p=>p.pea===s.transformerPea).long));
const example = sites[0];
assert.equal(isMeasurementSite({...example,lat:null}),false);
assert.equal(isMeasurementSite({...example,meterConfirmed:false}),false);
assert.equal(isMeasurementSite({...example,phase:'unknown'}),false);
assert.equal(isMeasurementSite({...example,voltage:200}),true);
assert.equal(isMeasurementSite({...example,voltage:230}),true);
assert.equal(isMeasurementSite({...example,voltage:0}),false);
assert.equal(isMeasurementSite({...example,voltage:NaN}),false);
assert.equal(meterVoltageStatus(199.99),'แรงดันตก');
assert.equal(meterVoltageStatus(200),'แรงดันไม่ตก');
assert.equal(meterVoltageStatus(230),'แรงดันไม่ตก');
assert.equal(isMeasurementSite({...example,terminalConfirmed:undefined}),false);
assert.equal(isMeasurementSite({...example,terminalConfirmed:false}),true);
assert.ok(sites.filter(s=>s.terminalConfirmed).every(s=>s.terminalDistanceM<=5));
console.log('PASS: all 43 targets have actual meter coordinates and source problem labels; 24 low / 19 normal voltage meters; 200 V boundary; phases, topology flags and invalid-data rejection.');
